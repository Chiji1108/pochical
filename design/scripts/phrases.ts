// Phrases.swift: BudouX, which the site runs on every Japanese string
// (packages/jsx), for the iOS app. SwiftUI breaks Japanese in the middle
// of a word (見えるよう／になります), and has nothing like CSS's keep-all, so
// a phrase's letters are joined by WORD JOINER instead. Android breaks
// between phrases itself (LineBreak.WordBreak.Phrase in the text styles).
import { jaModel } from "budoux";

const MODEL_DOC =
  "BudouX's Japanese model (https://github.com/google/budoux, Apache License 2.0), as the site's.";

export const swiftPhrases = (): string[] => [
  "import Foundation",
  "import SwiftUI",
  "",
  "/// Japanese broken between phrases, never in the middle of a word, as the",
  "/// site breaks it: BudouX finds the phrases.",
  "public enum Phrases {",
  `  /// ${MODEL_DOC}`,
  `  private static let modelJSON = #"${JSON.stringify(jaModel)}"#`,
  "",
  "  /// Each feature's scores, keyed by the UTF-16 code units of their letters.",
  "  private static let model: [String: [[UInt16]: Int]] = {",
  "    guard",
  "      let model = try? JSONDecoder().decode(",
  "        [String: [String: Int]].self, from: Data(modelJSON.utf8))",
  '    else { preconditionFailure("BudouX model") }',
  "    return model.mapValues { scores in",
  "      Dictionary(uniqueKeysWithValues: scores.map { (Array($0.key.utf16), $0.value) })",
  "    }",
  "  }()",
  "",
  "  private static let baseScore: Double =",
  "    -0.5 * Double(model.values.flatMap(\\.values).reduce(0, +))",
  "",
  "  /// The text's phrases, in order; together they are the text. Text with",
  "  /// no Japanese is one phrase, as on the site.",
  "  public static func split(_ text: String) -> [String] {",
  "    // BudouX reads text in UTF-16 code units, as JavaScript holds it, so an",
  "    // emoji outside the BMP is two; read the same way, it scores as the",
  "    // site's.",
  "    let units = Array(text.utf16)",
  "    guard units.count > 1, hasJapanese(text) else { return [text] }",
  "    // The units from `from` to `to`, cut to the text as JavaScript's",
  "    // substring cuts them.",
  "    func score(_ feature: String, _ from: Int, _ to: Int) -> Double {",
  "      let start = min(max(from, 0), units.count)",
  "      let end = min(max(to, 0), units.count)",
  "      return Double(model[feature]?[Array(units[start..<max(start, end)])] ?? 0)",
  "    }",
  "    var phrases: [String] = []",
  "    var start = 0",
  "    for index in 1..<units.count where !UTF16.isLeadSurrogate(units[index - 1]) {",
  "      let total =",
  "        baseScore",
  '        + score("UW1", index - 3, index - 2)',
  '        + score("UW2", index - 2, index - 1)',
  '        + score("UW3", index - 1, index)',
  '        + score("UW4", index, index + 1)',
  '        + score("UW5", index + 1, index + 2)',
  '        + score("UW6", index + 2, index + 3)',
  '        + score("BW1", index - 2, index)',
  '        + score("BW2", index - 1, index + 1)',
  '        + score("BW3", index, index + 2)',
  '        + score("TW1", index - 3, index)',
  '        + score("TW2", index - 2, index + 1)',
  '        + score("TW3", index - 1, index + 2)',
  '        + score("TW4", index, index + 3)',
  "      if total > 0 {",
  "        phrases.append(String(decoding: units[start..<index], as: UTF16.self))",
  "        start = index",
  "      }",
  "    }",
  "    phrases.append(String(decoding: units[start...], as: UTF16.self))",
  "    return phrases",
  "  }",
  "",
  "  /// Whether the text has Japanese in it, as the site asks: a letter whose",
  "  /// scripts take in Hiragana, Katakana or Han, 、 and ー among them.",
  "  static func hasJapanese(_ text: String) -> Bool {",
  "    text.contains(#/[\\p{scx=Hiragana}\\p{scx=Katakana}\\p{scx=Han}]/#)",
  "  }",
  "}",
  "",
  "extension String {",
  "  /// This text for showing, with each Japanese phrase kept whole on a line:",
  "  /// a WORD JOINER (U+2060), which nothing draws, between a phrase's",
  "  /// letters, so a line breaks only between phrases. A phrase too long for",
  "  /// its line still breaks. Keep the text itself as it is; only show this.",
  "  public var phrased: String {",
  "    guard Phrases.hasJapanese(self) else { return self }",
  "    return Phrases.split(self)",
  '      .map { phrase in phrase.map(String.init).joined(separator: "\\u{2060}") }',
  "      .joined()",
  "  }",
  "}",
  "",
  "extension Text {",
  "  /// Text whose Japanese breaks between phrases (String.phrased).",
  "  public init(phrased text: String) {",
  "    self.init(verbatim: text.phrased)",
  "  }",
  "}",
];
